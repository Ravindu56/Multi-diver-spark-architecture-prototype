#!/usr/bin/env python
# =============================================================================
# scripts/generate_datasets.py
# Permanent dataset generation fix — Phase 3 (Issues #8 and #9)
#
# PURPOSE
# -------
# Generate the input CSV files required by both the K-Means and LogReg
# MPI-Allreduce runners into SHARED_STORAGE_PATH (the NFS mount visible
# to all MPI ranks).  Uses the existing dataset_generator module — no new
# generation logic is introduced here.
#
# Run ONCE before any mpirun command:
#
#   python scripts/generate_datasets.py
#
# The script is IDEMPOTENT — it skips generation if the target file
# already exists (same size check).  Use --force to regenerate.
#
# DATASETS GENERATED
# ------------------
# K-Means  : {SHARED_STORAGE_PATH}/kmeans_data.csv
#             Numeric CSV, no header, 10 features, 3 Gaussian clusters.
#             Generated by generate_numeric_dataset().
#
# LogReg   : {SHARED_STORAGE_PATH}/logreg_data.csv
#             Numeric CSV with header row (f0,...,f9,label), binary labels,
#             linearly separable Gaussian clusters.
#             Generated by generate_classification_dataset().
#
# ENVIRONMENT OVERRIDES
# ---------------------
#   MPJ_SHARED_STORAGE   — NFS mount point  (default: ./shared_storage)
#   MPJ_KMEANS_DATA      — full path for kmeans CSV
#   MPJ_LOGREG_DATA      — full path for logreg CSV
#   MPJ_KMEANS_SIZE_MB   — target file size in MB  (default: 50)
#   MPJ_LOGREG_SIZE_MB   — target file size in MB  (default: 50)
#   MPJ_KMEANS_FEATURES  — number of feature columns  (default: 10)
#   MPJ_LOGREG_FEATURES  — number of feature columns  (default: 10)
#
# CLI FLAGS
#   --force          regenerate even if the file already exists
#   --kmeans-only    generate only the K-Means dataset
#   --logreg-only    generate only the LogReg dataset
#   --size-mb N      override size for both datasets
#   --num-features N override feature count for both datasets
#   --seed N         random seed (default: 42)
# =============================================================================

from __future__ import annotations

import argparse
import os
import sys

# Ensure project root is on the path so config and utils are importable
# whether this script is run from the project root or the scripts/ dir.
_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
_PROJECT_ROOT = os.path.dirname(_SCRIPT_DIR)
if _PROJECT_ROOT not in sys.path:
    sys.path.insert(0, _PROJECT_ROOT)

from mpj_spark.config import (  # noqa: E402
    KMEANS_DATASET_PATH,
    KMEANS_DATASET_SIZE_MB,
    KMEANS_NUM_FEATURES,
    LOGREG_DATASET_PATH,
    LOGREG_DATASET_SIZE_MB,
    LOGREG_NUM_FEATURES,
    SHARED_STORAGE_PATH,
)
from mpj_spark.utils.dataset_generator import (  # noqa: E402
    generate_classification_dataset,
    generate_numeric_dataset,
)


def _already_exists(path: str, size_mb: int) -> bool:
    """
    Return True if the file exists AND is at least 80% of the target size.
    The 80% threshold accounts for the fact that generate_* writes until
    the byte target is crossed, so actual size may differ by one row.
    """
    if not os.path.exists(path):
        return False
    actual_mb = os.path.getsize(path) / (1024 * 1024)
    return actual_mb >= size_mb * 0.8


def ensure_kmeans_dataset(
    path: str = KMEANS_DATASET_PATH,
    size_mb: int = KMEANS_DATASET_SIZE_MB,
    num_features: int = KMEANS_NUM_FEATURES,
    force: bool = False,
    seed: int = 42,
) -> str:
    """
    Generate the K-Means numeric CSV if it does not already exist.

    Parameters
    ----------
    path        : destination file path (default: KMEANS_DATASET_PATH from config)
    size_mb     : approximate file size in MB
    num_features: number of numeric feature columns
    force       : if True, regenerate even if the file exists
    seed        : unused (numeric generator does not take a seed; included
                  for API symmetry with ensure_logreg_dataset)

    Returns
    -------
    str — absolute path to the (now guaranteed-to-exist) file
    """
    if not force and _already_exists(path, size_mb):
        actual_mb = os.path.getsize(path) / (1024 * 1024)
        print(
            f"[generate_datasets] K-Means dataset already exists: {path} "
            f"({actual_mb:.1f} MB) — skipping.  Use --force to regenerate."
        )
        return os.path.abspath(path)

    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    generate_numeric_dataset(
        output_path=path,
        size_mb=size_mb,
        num_features=num_features,
    )
    return os.path.abspath(path)


def ensure_logreg_dataset(
    path: str = LOGREG_DATASET_PATH,
    size_mb: int = LOGREG_DATASET_SIZE_MB,
    num_features: int = LOGREG_NUM_FEATURES,
    force: bool = False,
    seed: int = 42,
) -> str:
    """
    Generate the LogReg classification CSV if it does not already exist.

    Parameters
    ----------
    path        : destination file path (default: LOGREG_DATASET_PATH from config)
    size_mb     : approximate file size in MB
    num_features: number of feature columns (label is always the last column)
    force       : if True, regenerate even if the file exists
    seed        : random seed for reproducibility (default: 42)

    Returns
    -------
    str — absolute path to the (now guaranteed-to-exist) file
    """
    if not force and _already_exists(path, size_mb):
        actual_mb = os.path.getsize(path) / (1024 * 1024)
        print(
            f"[generate_datasets] LogReg dataset already exists: {path} "
            f"({actual_mb:.1f} MB) — skipping.  Use --force to regenerate."
        )
        return os.path.abspath(path)

    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    generate_classification_dataset(
        output_path=path,
        size_mb=size_mb,
        num_features=num_features,
        noise=0.5,
        seed=seed,
    )
    return os.path.abspath(path)


# ---------------------------------------------------------------------------
# Public helper: called from allreduce.py __main__ blocks as a guard
# ---------------------------------------------------------------------------


def ensure_dataset(workload: str, input_file: str | None = None, **kwargs) -> str:
    """
    Ensure the required dataset exists for `workload` ("kmeans" or "logreg").
    If `input_file` is provided and already exists, return it unchanged.
    Otherwise generate to the config-default path and return that path.

    This is the single call inserted at the top of each runner's __main__
    block so a missing file auto-generates rather than crashing.

    Parameters
    ----------
    workload   : "kmeans" or "logreg"
    input_file : path provided by the user via --input (may be None or missing)
    **kwargs   : forwarded to ensure_kmeans_dataset / ensure_logreg_dataset

    Returns
    -------
    str — path to the dataset file (either the provided path or the generated one)
    """
    # If the caller provided a path and the file exists, trust it as-is.
    if input_file and os.path.exists(input_file):
        return input_file

    if input_file and not os.path.isfile(input_file):
        raise FileNotFoundError(
            f"Requested input file does not exist: {input_file}. "
            "Either provide a valid --input path or omit --input so the "
            "configured shared-storage dataset can be generated."
        )

    if workload == "kmeans":
        return ensure_kmeans_dataset(**kwargs)
    elif workload == "logreg":
        return ensure_logreg_dataset(**kwargs)
    else:
        raise ValueError(f"Unknown workload '{workload}'. Expected 'kmeans' or 'logreg'.")


# ---------------------------------------------------------------------------
# CLI entry-point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        prog="python scripts/generate_datasets.py",
        description="Generate K-Means and LogReg input datasets into "
        f"SHARED_STORAGE_PATH ({SHARED_STORAGE_PATH}).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Regenerate datasets even if they already exist.",
    )
    parser.add_argument(
        "--kmeans-only",
        action="store_true",
        help="Generate only the K-Means numeric dataset.",
    )
    parser.add_argument(
        "--logreg-only",
        action="store_true",
        help="Generate only the LogReg classification dataset.",
    )
    parser.add_argument(
        "--size-mb",
        type=int,
        default=None,
        help="Override file size in MB for both datasets "
        f"(defaults: kmeans={KMEANS_DATASET_SIZE_MB} MB, "
        f"logreg={LOGREG_DATASET_SIZE_MB} MB).",
    )
    parser.add_argument(
        "--num-features",
        type=int,
        default=None,
        help="Override number of feature columns for both datasets "
        f"(defaults: kmeans={KMEANS_NUM_FEATURES}, logreg={LOGREG_NUM_FEATURES}).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for dataset generation (default: 42).",
    )

    args = parser.parse_args()

    kmeans_size = args.size_mb or KMEANS_DATASET_SIZE_MB
    logreg_size = args.size_mb or LOGREG_DATASET_SIZE_MB
    kmeans_features = args.num_features or KMEANS_NUM_FEATURES
    logreg_features = args.num_features or LOGREG_NUM_FEATURES

    if kmeans_size <= 0:
        raise ValueError(f"K-Means dataset size must be positive, got {kmeans_size}")

    if logreg_size <= 0:
        raise ValueError(f"LogReg dataset size must be positive, got {logreg_size}")

    if kmeans_features < 2:
        raise ValueError(
            f"K-Means number of features must be at least 2, got {kmeans_features}"
        )

    if logreg_features < 2:
        raise ValueError(
            f"LogReg number of features must be at least 2, got {logreg_features}"
        )

    print(f"\n[generate_datasets] Shared storage: {SHARED_STORAGE_PATH}")
    print(f"[generate_datasets] K-Means  → {KMEANS_DATASET_PATH}")
    print(f"[generate_datasets] LogReg   → {LOGREG_DATASET_PATH}\n")

    generated = []


    if not args.logreg_only:
        path = ensure_kmeans_dataset(
            size_mb=kmeans_size,
            num_features=kmeans_features,
            force=args.force,
            seed=args.seed,
        )
        generated.append(("K-Means", path))

    if not args.kmeans_only:
        path = ensure_logreg_dataset(
            size_mb=logreg_size,
            num_features=logreg_features,
            force=args.force,
            seed=args.seed,
        )
        generated.append(("LogReg", path))

    print("\n[generate_datasets] Done.")
    for name, p in generated:
        size_mb = os.path.getsize(p) / (1024 * 1024)
        print(f"  {name:8s}: {p}  ({size_mb:.1f} MB)")
    print()
    print("Run K-Means:")
    print(
        f"  mpirun -n 3 python -m mpj_spark.applications.kmeans.allreduce \\'\n"
        f"      --input {KMEANS_DATASET_PATH} --k 5 --max-iter 20"
    )
    print("\nRun LogReg:")
    print(
        f"  mpirun -n 3 python -m mpj_spark.applications.logreg.allreduce \\'\n"
        f"      --input {LOGREG_DATASET_PATH} --epochs 30 --lr 0.01"
    )
